"""Markdown and HTML report rendering for findings, IOCs, and timeline."""
from __future__ import annotations

import html
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

REPORT_KINDS = ("markdown", "html", "both")


def _format_ts(t: float) -> str:
    return datetime.fromtimestamp(float(t), timezone.utc).strftime(
        "%Y-%m-%d %H:%M:%S UTC"
    )


@dataclass
class ReportData:
    """Everything a written report needs besides the output path."""

    case_id: str
    pcap_name: str
    pcap_bytes: int
    sha256: str
    unchanged: bool
    packets: int
    t0: float
    t1: float
    custody: str
    cross_check: str
    findings: list[tuple[str, str, str]] = field(default_factory=list)
    events: list[tuple] = field(default_factory=list)
    iocs: list[tuple[str, str, str]] = field(default_factory=list)
    tls_sni: list[tuple[str, str, int, str]] = field(default_factory=list)
    talkers: list[tuple[str, str, int]] = field(default_factory=list)
    summary: str = ""


def render_markdown(data: ReportData) -> str:
    """Return the Markdown report body, including a trailing newline."""
    md = [
        f"# Network Forensics Report - {data.case_id}",
        "",
        "## Evidence",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Capture | `{data.pcap_name}` ({data.pcap_bytes:,} bytes) |",
        f"| SHA-256 | `{data.sha256}` |",
        f"| Unchanged after analysis | {'YES' if data.unchanged else 'NO'} |",
        f"| Packets | {data.packets} |",
        f"| Time span | {_format_ts(data.t0)} to {_format_ts(data.t1)} |",
        f"| Custody log | {data.custody} |",
        f"| Cross-check | {data.cross_check} |",
        "",
        "## Executive summary",
        "",
        data.summary,
        "",
        "## Findings",
        "",
        "| Severity | Finding | Detail |",
        "|---|---|---|",
    ]
    md += [f"| {s} | {t} | {d} |" for s, t, d in data.findings]
    md += [
        "",
        "## Timeline (non-informational events)",
        "",
        "| Time | Sev | Category | Detail | ATT&CK |",
        "|---|---|---|---|---|",
    ]
    md += [
        f"| {_format_ts(e[0])} | {e[1]} | {e[2]} | {e[3]} | {e[4]} |"
        for e in data.events
        if e[1] != "INFO"
    ]
    md += [
        "",
        "## Indicators of compromise",
        "",
        "| Type | Value | Context |",
        "|---|---|---|",
    ]
    md += [f"| {k} | `{v}` | {c} |" for k, v, c in data.iocs]
    md += [
        "",
        "## TLS SNI (informational)",
        "",
        "Hostnames from TLS ClientHello. These are visited-site context, "
        "not findings or indicators of compromise.",
        "",
        "| Client | Server | Port | Hostname |",
        "|---|---|---|---|",
    ]
    sni_rows = [
        f"| {src} | {dst} | {dport} | `{host}` |"
        for src, dst, dport, host in sorted(data.tls_sni)
    ]
    md += sni_rows or ["| — | — | — | none observed |"]
    md += [
        "",
        "## Top talkers (bytes)",
        "",
        "| Source | Destination | Bytes |",
        "|---|---|---|",
    ]
    md += [f"| {s} | {d} | {b:,} |" for s, d, b in data.talkers]
    md += [
        "",
        "## Limitations",
        "",
        "- Heuristic thresholds need baselining on real networks to cut false positives.",
        "- Encrypted traffic (TLS/HTTPS) hides payloads; SNI is read from ClientHello (no decrypt).",
        "- Passwords are masked in this report; full values stay only in the original evidence.",
        "- Generated by [pcaplens](https://github.com/GameMaster007/pcaplens).",
        "",
    ]
    return "\n".join(md)


def render_html(data: ReportData) -> str:
    """Self-contained HTML report. No extra dependencies."""
    esc = html.escape
    findings_rows = "".join(
        f"<tr><td>{esc(s)}</td><td>{esc(t)}</td><td>{esc(d)}</td></tr>"
        for s, t, d in data.findings
    ) or "<tr><td colspan='3'>None</td></tr>"
    timeline_rows = "".join(
        f"<tr><td>{esc(_format_ts(e[0]))}</td><td>{esc(e[1])}</td>"
        f"<td>{esc(e[2])}</td><td>{esc(e[3])}</td><td>{esc(e[4])}</td></tr>"
        for e in data.events
        if e[1] != "INFO"
    ) or "<tr><td colspan='5'>None</td></tr>"
    ioc_rows = "".join(
        f"<tr><td>{esc(k)}</td><td><code>{esc(v)}</code></td><td>{esc(c)}</td></tr>"
        for k, v, c in data.iocs
    ) or "<tr><td colspan='3'>None</td></tr>"
    sni_rows = "".join(
        f"<tr><td>{esc(src)}</td><td>{esc(dst)}</td><td>{dport}</td>"
        f"<td><code>{esc(host)}</code></td></tr>"
        for src, dst, dport, host in sorted(data.tls_sni)
    ) or "<tr><td colspan='4'>none observed</td></tr>"
    talk_rows = "".join(
        f"<tr><td>{esc(s)}</td><td>{esc(d)}</td><td>{b:,}</td></tr>"
        for s, d, b in data.talkers
    ) or "<tr><td colspan='3'>None</td></tr>"
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Network Forensics Report - {esc(data.case_id)}</title>
<style>
body {{ font-family: system-ui, sans-serif; margin: 2rem auto; max-width: 960px; color: #1a1a1a; }}
table {{ border-collapse: collapse; width: 100%; margin: 1rem 0; }}
th, td {{ border: 1px solid #ccc; padding: 0.4rem 0.6rem; text-align: left; vertical-align: top; }}
th {{ background: #f4f4f4; }}
code {{ font-size: 0.9em; }}
h1, h2 {{ color: #111; }}
.note {{ color: #444; }}
</style>
</head>
<body>
<h1>Network Forensics Report - {esc(data.case_id)}</h1>
<h2>Evidence</h2>
<table>
<tr><th>Field</th><th>Value</th></tr>
<tr><td>Capture</td><td><code>{esc(data.pcap_name)}</code> ({data.pcap_bytes:,} bytes)</td></tr>
<tr><td>SHA-256</td><td><code>{esc(data.sha256)}</code></td></tr>
<tr><td>Unchanged after analysis</td><td>{"YES" if data.unchanged else "NO"}</td></tr>
<tr><td>Packets</td><td>{data.packets}</td></tr>
        <tr><td>Time span</td><td>{esc(_format_ts(data.t0))} to {esc(_format_ts(data.t1))}</td></tr>
<tr><td>Custody log</td><td>{esc(data.custody)}</td></tr>
<tr><td>Cross-check</td><td>{esc(data.cross_check)}</td></tr>
</table>
<h2>Executive summary</h2>
<p>{esc(data.summary)}</p>
<h2>Findings</h2>
<table>
<tr><th>Severity</th><th>Finding</th><th>Detail</th></tr>
{findings_rows}
</table>
<h2>Timeline (non-informational events)</h2>
<table>
<tr><th>Time</th><th>Sev</th><th>Category</th><th>Detail</th><th>ATT&amp;CK</th></tr>
{timeline_rows}
</table>
<h2>Indicators of compromise</h2>
<table>
<tr><th>Type</th><th>Value</th><th>Context</th></tr>
{ioc_rows}
</table>
<h2>TLS SNI (informational)</h2>
<p class="note">Hostnames from TLS ClientHello. These are visited-site context,
not findings or indicators of compromise.</p>
<table>
<tr><th>Client</th><th>Server</th><th>Port</th><th>Hostname</th></tr>
{sni_rows}
</table>
<h2>Top talkers (bytes)</h2>
<table>
<tr><th>Source</th><th>Destination</th><th>Bytes</th></tr>
{talk_rows}
</table>
<h2>Limitations</h2>
<ul>
<li>Heuristic thresholds need baselining on real networks to cut false positives.</li>
<li>Encrypted traffic (TLS/HTTPS) hides payloads; SNI is read from ClientHello (no decrypt).</li>
<li>Passwords are masked in this report; full values stay only in the original evidence.</li>
<li>Generated by pcaplens.</li>
</ul>
</body>
</html>
"""


def write_reports(out_dir: Any, data: ReportData, kind: str) -> list[Any]:
    """Write markdown and/or HTML under *out_dir*. Return paths written."""
    if kind not in REPORT_KINDS:
        allowed = " or ".join(repr(item) for item in REPORT_KINDS)
        raise ValueError(f"unsupported report kind {kind!r}; use {allowed}")
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written: list[Any] = []
    if kind in ("markdown", "both"):
        path = out / "report.md"
        path.write_text(render_markdown(data), encoding="utf-8")
        written.append(path)
    if kind in ("html", "both"):
        path = out / "report.html"
        path.write_text(render_html(data), encoding="utf-8")
        written.append(path)
    return written
